import JSZip from 'jszip';
import { ComponentRegistryItem } from '@/types/registry';

export interface ComponentExportOptions {
  component: ComponentRegistryItem;
  props: Record<string, any>;
  reactCode: string;
  htmlCode: string;
  cssCode?: string;
  tailwindCode?: string;
}

/**
 * Generates a clean, production-ready standalone ZIP package
 * containing TypeScript component source, CSS tokens, package.json, and usage README.
 */
export async function exportComponentZip(options: ComponentExportOptions): Promise<Blob> {
  const { component, props, reactCode, htmlCode, cssCode, tailwindCode } = options;
  const zip = new JSZip();

  const compName = component.id.charAt(0).toUpperCase() + component.id.slice(1);

  // 1. Component TypeScript/React file
  zip.file(
    `src/components/${compName}.tsx`,
    `// Generated by Mahi UI Component Playground
${reactCode}
`
  );

  // 2. Component HTML + CSS Vanilla alternative
  zip.file(
    `src/vanilla/${component.id}.html`,
    `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>${component.title} — Mahi UI Export</title>
  <link rel="stylesheet" href="./style.css">
</head>
<body>
${htmlCode}
</body>
</html>
`
  );

  // 3. CSS Tokens & Stylesheet
  const defaultTokensCss = `:root {
  --accent-primary: #10b981;
  --accent-hover: #059669;
  --accent-light: rgba(16, 185, 129, 0.15);
  --accent-glow: rgba(16, 185, 129, 0.35);
  --bg-primary: #090d16;
  --bg-secondary: #0f172a;
  --bg-card: #161e2e;
  --text-primary: #f8fafc;
  --text-secondary: #94a3b8;
  --border-color: rgba(255, 255, 255, 0.08);
  --radius-sm: 6px;
  --radius-md: 10px;
  --radius-lg: 16px;
}

body {
  font-family: system-ui, -apple-system, sans-serif;
  background: var(--bg-primary);
  color: var(--text-primary);
  padding: 2rem;
  display: flex;
  justify-content: center;
  align-items: center;
  min-height: 100vh;
}
`;

  zip.file(`src/vanilla/style.css`, `${defaultTokensCss}\n${cssCode || ''}`);

  // 4. Props and Configuration JSON
  zip.file(
    `config.json`,
    JSON.stringify(
      {
        componentId: component.id,
        title: component.title,
        category: component.category,
        exportedAt: new Date().toISOString(),
        props,
        accessibility: component.accessibility
      },
      null,
      2
    )
  );

  // 5. Standalone package.json
  const standalonePackageJson = {
    name: `@mahi-ui/${component.id}`,
    version: '1.0.0',
    description: `Exported ${component.title} from Mahi UI Component Playground`,
    main: `src/components/${compName}.tsx`,
    scripts: {
      build: 'tsc --noEmit'
    },
    dependencies: {
      react: '^19.0.0',
      'react-dom': '^19.0.0',
      clsx: '^2.1.1'
    },
    devDependencies: {
      '@types/react': '^19.0.0',
      '@types/react-dom': '^19.0.0',
      typescript: '^5.0.0'
    }
  };

  zip.file('package.json', JSON.stringify(standalonePackageJson, null, 2));

  // 6. Comprehensive README.md
  const readmeContent = `# ${component.title} — Mahi UI Component Package

Exported directly from the **[Mahi UI Component Playground](https://github.com/mahi-developer-universe/Mahi-UI-Component-Playground)**.

## Overview
- **Category:** ${component.category}
- **Component ID:** \`${component.id}\`
- **Configured Props:** 
\`\`\`json
${JSON.stringify(props, null, 2)}
\`\`\`

## Installation

\`\`\`bash
npm install clsx react react-dom
\`\`\`

## React / Next.js Usage

\`\`\`tsx
import { ${compName} } from './src/components/${compName}';

export default function Page() {
  return (
    <main>
      <${compName} />
    </main>
  );
}
\`\`\`

## Accessibility & Standards
- **Role:** \`${component.accessibility?.role || 'component'}\`
- **Keyboard Navigation:** ${component.accessibility?.keyboardNavigation || 'Standard Tab / Enter / Space interactions.'}
- **WCAG Notes:** ${component.accessibility?.wcagNotes || 'Meets WCAG AA text contrast standards.'}

## License
MIT — Authored by Mahi Developer Universe.
`;

  zip.file('README.md', readmeContent);

  // 7. Tailwind Config snippet if available
  if (tailwindCode) {
    zip.file(
      'tailwind.snippet.tsx',
      `// Tailwind CSS Variant\nexport const TailwindVariant = () => (\n  ${tailwindCode}\n);\n`
    );
  }

  // Generate ZIP Blob
  return await zip.generateAsync({ type: 'blob' });
}
